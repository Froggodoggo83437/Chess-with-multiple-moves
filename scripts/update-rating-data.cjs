const fs = require('node:fs'), path = require('node:path'), crypto = require('node:crypto');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const read = name => JSON.parse(fs.readFileSync(path.join(root, 'benchmarks', name)));
const hash = file => crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
const estimates = read('calibration-estimates.json'), receipt = read('calibration-verification.json');
assert.equal(receipt.status, 'passed');
assert.equal(receipt.calibrationSha256, hash(path.join(root, 'benchmarks/calibration-games.json')));
assert.equal(estimates.calibrationSha256, receipt.calibrationSha256);
assert.equal(estimates.rulesSha256, hash(path.join(root, 'src/rules.cjs')));
assert.equal(estimates.rows.length, 32);
const data = {
  rulesSha256: estimates.rulesSha256, calibrationSha256: estimates.calibrationSha256,
  games: estimates.totals.games, budgetMs: 150,
  rows: estimates.rows.map(row => {
    const { target, pointEstimate, estimateStatus, simultaneous95 } = row;
    return { target, pointEstimate, estimateStatus, simultaneous95 };
  })
};
fs.writeFileSync(path.join(root, 'src/calibration-data.cjs'), '// Generated by npm run ratings:update from verified reference data; not human or custom-turn Elo.\nmodule.exports = ' + JSON.stringify(data) + ';\n');
console.log('Updated embedded reference estimates from the verified calibration. Run npm run build.');
